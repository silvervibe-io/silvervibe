/**
 * Single source of truth for Firebase *web* config: repo-root `.env`
 * (and the same vars in CI / Cloudflare Pages at build time).
 *
 * Writes gitignored `firebase-web.local.ts` for Angular imports.
 * Does not touch Nest Admin credentials (those stay server-side only).
 */
import { config as loadEnv } from 'dotenv';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
loadEnv({ path: join(root, '.env') });

function env(name) {
  const raw = process.env[name] ?? '';
  return raw.replace(/^["']|["']$/g, '').trim();
}

const firebaseWeb = {
  apiKey: env('FIREBASE_API_KEY'),
  authDomain: env('FIREBASE_AUTH_DOMAIN'),
  projectId: env('FIREBASE_PROJECT_ID'),
  appId: env('FIREBASE_APP_ID'),
};

const body = `/** Generated by tools/sync-firebase-web-from-env.mjs — do not edit or commit. */
export const firebaseWeb = ${JSON.stringify(firebaseWeb, null, 2)} as const;
`;

for (const app of ['silvervibe', 'vibestandup']) {
  const out = join(
    root,
    'apps',
    app,
    'src',
    'environments',
    'firebase-web.local.ts',
  );
  writeFileSync(out, body, 'utf8');
}

if (!firebaseWeb.apiKey || !firebaseWeb.projectId) {
  console.warn(
    'sync-firebase-web-from-env: FIREBASE_API_KEY / FIREBASE_PROJECT_ID empty — AuthService will stay idle until .env is filled.',
  );
} else {
  console.log(
    'sync-firebase-web-from-env: wrote firebase-web.local.ts for silvervibe + vibestandup',
  );
}
