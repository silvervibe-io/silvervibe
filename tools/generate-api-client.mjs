/**
 * Generates Angular services + DTOs from `openapi/silvervibe.openapi.json`
 * via OpenAPI Generator (same toolchain as funxtion-portal).
 *
 * Layout:
 *   libs/shared/api-client/src/lib/generated/api/    — one *DataService per tag
 *   libs/shared/api-client/src/lib/generated/model/  — one file per schema
 *
 * Requires a Java runtime (OpenAPI Generator runs a JAR).
 *
 * Usage: npm run api-client
 *        npm run openapi:client  — regenerates OpenAPI first, then this
 */
import { spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = join(root, 'openapi', 'silvervibe.openapi.json');
const outDir = join(root, 'libs/shared/api-client/src/lib/generated');
const cliJs = join(
  root,
  'node_modules',
  '@openapitools',
  'openapi-generator-cli',
  'main.js',
);

if (!existsSync(spec)) {
  console.error(
    `Missing ${spec}. Run npm run openapi first to export the Nest Swagger document.`,
  );
  process.exit(1);
}

if (!existsSync(cliJs)) {
  console.error(
    'Missing @openapitools/openapi-generator-cli. Run npm install.',
  );
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

// Wipe previous generation (keep ignore files if present).
for (const name of readdirSync(outDir)) {
  if (name === '.openapi-generator-ignore' || name === '.gitignore') {
    continue;
  }
  rmSync(join(outDir, name), { recursive: true, force: true });
}

console.log(`Input:  ${spec}`);
console.log(`Output: ${outDir}`);

const result = spawnSync(
  process.execPath,
  [cliJs, 'generate', '--generator-key', 'silvervibe'],
  {
    cwd: root,
    stdio: 'inherit',
    env: process.env,
  },
);

if (result.status !== 0) {
  console.error(
    'OpenAPI Generator failed. Install a Java 11+ runtime (required by the generator JAR).',
  );
  process.exit(result.status ?? 1);
}

const indexPath = join(outDir, 'index.ts');
if (!existsSync(indexPath)) {
  console.error(`Expected generated barrel missing: ${indexPath}`);
  process.exit(1);
}

// Drop generator scaffolding we do not want in the repo.
for (const junk of ['git_push.sh', 'README.md']) {
  const p = join(outDir, junk);
  if (existsSync(p)) {
    rmSync(p, { force: true });
  }
}

writeFileSync(
  join(outDir, '.generated'),
  'Generated by tools/generate-api-client.mjs — do not edit by hand.\n',
  'utf8',
);

/**
 * OpenAPI Generator's `api/api.ts` imports every *DataService into an `APIS`
 * array. That keeps the whole client graph alive through the package barrel.
 * Rewrite to pure re-exports so unused addon services can tree-shake.
 *
 * Read first (no existsSync) to avoid TOCTOU; skip if the generator omitted it.
 */
const apiBarrelPath = join(outDir, 'api', 'api.ts');
let apiBarrelSource;
try {
  apiBarrelSource = readFileSync(apiBarrelPath, 'utf8');
} catch (err) {
  const code =
    err && typeof err === 'object' && 'code' in err
      ? String(err.code)
      : undefined;
  if (code !== 'ENOENT') {
    throw err;
  }
  console.warn('api/api.ts missing after generate; skipped tree-shake slim.');
}

if (apiBarrelSource !== undefined) {
  const reExports = [
    ...apiBarrelSource.matchAll(/^export \* from ('[^']+');$/gm),
  ].map((m) => m[0]);
  if (reExports.length === 0) {
    console.warn(
      'Could not find export * lines in api/api.ts; left generator output as-is.',
    );
  } else {
    const slim = [
      '/**',
      ' * Tree-shakeable re-exports of OpenAPI *DataService classes.',
      ' *',
      ' * OpenAPI Generator normally emits side-effect imports + an `APIS` array',
      ' * that keeps every service alive. Rewritten by generate-api-client.mjs.',
      ' */',
      ...reExports,
      '',
    ].join('\n');
    writeFileSync(apiBarrelPath, slim, 'utf8');
    console.log('Slimmed api/api.ts (removed APIS array for tree-shaking).');
  }
}
console.log(`Wrote Angular client under ${outDir}`);
console.log('  api/   — DataServices (one file per OpenAPI tag)');
console.log('  model/ — DTO interfaces (one file per schema)');
