/**
 * Generates Angular services + DTOs from `openapi/silvervibe.openapi.json`
 * via OpenAPI Generator (same toolchain as funxtion-portal).
 *
 * Layout:
 *   libs/shared/api-client/src/lib/generated/api/    — one *DataService per tag
 *   libs/shared/api-client/src/lib/generated/model/  — one file per schema
 *
 * Requires a Java runtime (OpenAPI Generator runs a JAR).
 *
 * Usage: npm run api-client
 *        npm run openapi:client  — regenerates OpenAPI first, then this
 */
import { spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = join(root, 'openapi', 'silvervibe.openapi.json');
const outDir = join(root, 'libs/shared/api-client/src/lib/generated');
const cliJs = join(
  root,
  'node_modules',
  '@openapitools',
  'openapi-generator-cli',
  'main.js',
);

if (!existsSync(spec)) {
  console.error(
    `Missing ${spec}. Run npm run openapi first to export the Nest Swagger document.`,
  );
  process.exit(1);
}

if (!existsSync(cliJs)) {
  console.error(
    'Missing @openapitools/openapi-generator-cli. Run npm install.',
  );
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

// Wipe previous generation (keep ignore files if present).
for (const name of readdirSync(outDir)) {
  if (name === '.openapi-generator-ignore' || name === '.gitignore') {
    continue;
  }
  rmSync(join(outDir, name), { recursive: true, force: true });
}

console.log(`Input:  ${spec}`);
console.log(`Output: ${outDir}`);

const result = spawnSync(
  process.execPath,
  [cliJs, 'generate', '--generator-key', 'silvervibe'],
  {
    cwd: root,
    stdio: 'inherit',
    env: process.env,
  },
);

if (result.status !== 0) {
  console.error(
    'OpenAPI Generator failed. Install a Java 11+ runtime (required by the generator JAR).',
  );
  process.exit(result.status ?? 1);
}

const indexPath = join(outDir, 'index.ts');
if (!existsSync(indexPath)) {
  console.error(`Expected generated barrel missing: ${indexPath}`);
  process.exit(1);
}

// Drop generator scaffolding we do not want in the repo.
for (const junk of ['git_push.sh', 'README.md']) {
  const p = join(outDir, junk);
  if (existsSync(p)) {
    rmSync(p, { force: true });
  }
}

writeFileSync(
  join(outDir, '.generated'),
  'Generated by tools/generate-api-client.mjs — do not edit by hand.\n',
  'utf8',
);

console.log(`Wrote Angular client under ${outDir}`);
console.log('  api/   — DataServices (one file per OpenAPI tag)');
console.log('  model/ — DTO interfaces (one file per schema)');
