/**
 * Syncs public Angular config from repo-root `.env` into gitignored local modules.
 * - firebase-web.local.ts (Firebase Auth web)
 * - growthbook.local.ts (OpenFeature / GrowthBook client key)
 *
 * Nest Admin / GROWTHBOOK_SERVER_KEY stay server-side only (not written here).
 */
import { config as loadEnv } from 'dotenv';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
loadEnv({ path: join(root, '.env') });

function env(name) {
  const raw = process.env[name] ?? '';
  return raw.replace(/^["']|["']$/g, '').trim();
}

const firebaseWeb = {
  apiKey: env('FIREBASE_API_KEY'),
  authDomain: env('FIREBASE_AUTH_DOMAIN'),
  projectId: env('FIREBASE_PROJECT_ID'),
  appId: env('FIREBASE_APP_ID'),
};

const growthbook = {
  clientKey: env('GROWTHBOOK_CLIENT_KEY'),
  apiHost: env('GROWTHBOOK_API_HOST') || 'https://cdn.growthbook.io',
};

const firebaseBody = `/** Generated by tools/sync-angular-env-from-env.mjs — do not edit or commit. */
export const firebaseWeb = ${JSON.stringify(firebaseWeb, null, 2)} as const;
`;

const growthbookBody = `/** Generated by tools/sync-angular-env-from-env.mjs — do not edit or commit. */
export const growthbook = ${JSON.stringify(growthbook, null, 2)} as const;
`;

for (const app of ['silvervibe', 'vibestandup']) {
  const dir = join(root, 'apps', app, 'src', 'environments');
  writeFileSync(join(dir, 'firebase-web.local.ts'), firebaseBody, 'utf8');
  writeFileSync(join(dir, 'growthbook.local.ts'), growthbookBody, 'utf8');
}

if (!firebaseWeb.apiKey || !firebaseWeb.projectId) {
  console.warn(
    'sync-angular-env: FIREBASE_API_KEY / FIREBASE_PROJECT_ID empty — AuthService stays idle until .env is filled.',
  );
} else {
  console.log('sync-angular-env: wrote firebase-web.local.ts');
}

if (!growthbook.clientKey) {
  console.warn(
    'sync-angular-env: GROWTHBOOK_CLIENT_KEY empty — Angular OpenFeature uses static defaults.',
  );
} else {
  console.log('sync-angular-env: wrote growthbook.local.ts');
}
